function dump(obj: unknown): string {
  // lineWidth -1 disables folding so multi-line strings emit as literal blocks (|-).
  return GENERATED_HEADER + yamlDump(obj, { lineWidth: -1, noRefs: true, quotingType: '"' });
}

function write(path: string, content: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, "utf-8");
  console.log(`  wrote ${path.replace(ROOT + "/", "")}`);
}

function main() {
  const cases = JSON.parse(
    readFileSync(join(ROOT, "evals", "eval_cases.json"), "utf-8")
  ) as EvalCase[];

  const agent = buildAgentDefinition();
  const skillMd = buildSkillMarkdown();

  console.log("Exporting Atlas AI agent-as-code artifacts…");

  // Toolkit module layout
  write(join(MODULE_AGENTS_DIR, `${AGENT_EXTERNAL_ID}.Agent.yaml`), dump(agent));
  write(
    join(MODULE_AGENTS_DIR, `${SKILL_EXTERNAL_ID}.Skill.yaml`),
    dump({ externalId: SKILL_EXTERNAL_ID })
  );
  write(join(MODULE_AGENTS_DIR, `${SKILL_EXTERNAL_ID}.Skill.md`), skillMd);

  // Cognite CLI project layout (same agent YAML + CLI-only eval suite)
  write(join(CLI_AGENT_DIR, "pharmaops-triage.agent.yaml"), dump(agent));
  write(join(CLI_AGENT_DIR, "eval", "eval.yaml"), dump(buildEvalSuite(cases)));

  console.log(`Done — ${cases.length} eval cases exported.`);
}

main();
