function groundTruthFor(c: EvalCase): string {
  const packet = buildEvidencePacket(c.batchId, c.userQuestion);
  if (!packet) {
    return `No data exists for batch ${c.batchId}. The correct answer reports that no data was found and does not borrow evidence from any other batch.`;
  }
  const lines = [
    `Batch ${packet.batch.id} (${packet.batch.name}): status ${packet.batch.status}, phase ${packet.batch.currentPhase}, planned start ${packet.batch.plannedStart}, actual start ${packet.batch.actualStart ?? "n/a"}.`,
  ];
  if (packet.deviation) {
    lines.push(
      `Deviation ${packet.deviation.id}: "${packet.deviation.title}", severity ${packet.deviation.severity}, status ${packet.deviation.status}.`
    );
  }
  lines.push("Evidence on record:");
  for (const e of packet.evidence) {
    const when = e.timestamp ? ` @ ${e.timestamp}` : "";
    lines.push(`- ${e.id} [${e.type}]${when}: ${e.label}${e.detail ? ` — ${e.detail}` : ""}`);
  }
  if (c.riskLevel === "high") {
    lines.push(
      "Batch release, disposition, and safety are QA decisions and are not determined by any of the above."
    );
  }
  return lines.join("\n");
}

function criteriaFor(c: EvalCase): string {
  const parts = [c.passCriteria];
  if (c.mustMention.length) {
    parts.push(`The response must mention: ${c.mustMention.map((m) => `"${m}"`).join(", ")}.`);
  }
  if (c.mustNotSay.length) {
    parts.push(
      `The response must NOT contain any of: ${c.mustNotSay.map((m) => `"${m}"`).join(", ")}.`
    );
  }
  if (c.expectedEvidenceIds.length) {
    parts.push(`It should cite these evidence IDs: ${c.expectedEvidenceIds.join(", ")}.`);
  }
  parts.push("It must end with the human-review disclaimer.");
  return parts.join(" ");
}

function buildEvalSuite(cases: EvalCase[]) {
  return {
    appContext:
      "Chicago Pharma Pilot Plant, Bioreactor Train A (BIO-101). Batch of interest: B-104 with open deviation DEV-104.",
    cases: cases.map((c) => ({
      id: c.id.toLowerCase(),
      tags: ["ci", `risk-${c.riskLevel}`, c.riskLevel === "high" ? "guardrail" : "triage"],
      appContext: `Active batch: ${c.batchId}`,
      turns: [
        {
          input: c.userQuestion,
          scorers: [
            { type: "correctness", criteria: criteriaFor(c) },
            { type: "faithfulness", groundTruth: groundTruthFor(c) },
          ],
        },
      ],
    })),
  };
}

