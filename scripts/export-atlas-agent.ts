/**
 * Export the copilot's guardrails, skill, and eval suite as Cognite Atlas AI
 * "agents as code" artifacts.
 *
 *   npm run export:atlas
 *
 * Generates (do not hand-edit — re-run the script):
 *
 *   cdf/modules/pharmaops_deviation/agents/
 *     pharmaops_triage.Agent.yaml           Toolkit agent resource
 *     pharmaops_deviation_triage.Skill.yaml Toolkit skill identity
 *     pharmaops_deviation_triage.Skill.md   Skill body (Agent Skills SKILL.md format)
 *
 *   cdf/agents/pharmaops-triage/
 *     pharmaops-triage.agent.yaml           Cognite CLI agent (same shape as Toolkit)
 *     eval/eval.yaml                        Cognite CLI eval suite (CLI-only format)
 *
 * The agent instructions come from server/agent/guardrails.ts, and every eval
 * case comes from evals/eval_cases.json, with `faithfulness` ground truth built
 * from the real evidence packet. So the local deterministic evals and the Atlas
 * evals always test the same behavior.
 *
 * Formats follow:
 *   https://docs.cognite.com/dev/sdks/cognite-cli/agent-yaml
 *   https://docs.cognite.com/dev/sdks/cognite-cli/agents-eval
 *   https://docs.cognite.com/cdf/deploy/cdf_toolkit/references/resource_library#agent-skills
 */

import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { dump as yamlDump } from "js-yaml";
import {
  AGENT_IDENTITY,
  HUMAN_REVIEW_DISCLAIMER,
  UNIVERSAL_RULES,
} from "../server/agent/guardrails";
import { buildEvidencePacket } from "../server/agent/evidenceBuilder";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

const AGENT_EXTERNAL_ID = "pharmaops_triage";
const SKILL_EXTERNAL_ID = "pharmaops_deviation_triage";
const MODULE_AGENTS_DIR = join(ROOT, "cdf", "modules", "pharmaops_deviation", "agents");
const CLI_AGENT_DIR = join(ROOT, "cdf", "agents", "pharmaops-triage");

interface EvalCase {
  id: string;
  userQuestion: string;
  batchId: string;
  expectedEvidenceIds: string[];
  mustMention: string[];
  mustNotSay: string[];
  riskLevel: "low" | "medium" | "high";
  passCriteria: string;
}

const GENERATED_HEADER =
  "# GENERATED by scripts/export-atlas-agent.ts — edit server/agent/guardrails.ts or evals/eval_cases.json instead.\n";

